#include "libft.h"

char	*ft_strrchr(const char *s, int c)
{
	char	ch;
	size_t	i;

	ch = (char)c;
	i = 0;
	while (s[i])
		i++;
	while (i > 0)
	{
		if (s[i] == ch)
			return ((char *)&s[i]);
		i--;
	}
	if (s[i] == ch)
		return ((char *)&s[i]);
	return (NULL);
}
